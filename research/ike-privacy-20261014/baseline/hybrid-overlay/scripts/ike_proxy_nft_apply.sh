#!/usr/bin/env bash
set -euo pipefail

# nftables rules for Debian 13 / Linux 6.x.
# Redirect only local strongSwan IKE control traffic to the Python adapter.
# ESP must NOT be redirected.

MARK_HEX="0x53"

# Per-destination capture ports. The Python adapter uses the selected port as
# dst_user hint because REDIRECT on OUTPUT can hide original destination as
# 127.0.0.1.
USER1_IP="192.168.101.10"; USER1_CAP500="15101"; USER1_CAP4500="15201"
USER2_IP="192.168.102.10"; USER2_CAP500="15102"; USER2_CAP4500="15202"
USER3_IP="192.168.103.10"; USER3_CAP500="15103"; USER3_CAP4500="15203"
USER4_IP="192.168.104.10"; USER4_CAP500="15104"; USER4_CAP4500="15204"
USER5_IP="192.168.105.10"; USER5_CAP500="15105"; USER5_CAP4500="15205"
USER6_IP="192.168.106.10"; USER6_CAP500="15106"; USER6_CAP4500="15206"
USER7_IP="192.168.107.10"; USER7_CAP500="15107"; USER7_CAP4500="15207"
USER8_IP="192.168.108.10"; USER8_CAP500="15108"; USER8_CAP4500="15208"
USER9_IP="192.168.109.10"; USER9_CAP500="15109"; USER9_CAP4500="15209"
USER10_IP="192.168.110.10"; USER10_CAP500="15110"; USER10_CAP4500="15210"
USER11_IP="10.255.11.2"; USER11_CAP500="15111"; USER11_CAP4500="15211"
USER12_IP="10.255.12.2"; USER12_CAP500="15112"; USER12_CAP4500="15212"
USER13_IP="192.168.113.199"; USER13_CAP500="15113"; USER13_CAP4500="15213"

if [[ "${EUID}" -ne 0 ]]; then
  echo "Run as root" >&2
  exit 1
fi

command -v nft >/dev/null 2>&1 || { echo "nft is not installed" >&2; exit 1; }

# Required for transparent source binding in ike_proxy.py.
sysctl -w net.ipv4.ip_nonlocal_bind=1 >/dev/null
sysctl -w net.ipv4.conf.all.rp_filter=0 >/dev/null || true
sysctl -w net.ipv4.conf.default.rp_filter=0 >/dev/null || true

# Recreate a dedicated table. This is safer for lab use than appending duplicates.
nft list table inet ikeproxy >/dev/null 2>&1 && nft delete table inet ikeproxy

nft -f - <<NFT
add table inet ikeproxy
add chain inet ikeproxy output_raw { type filter hook output priority raw; policy accept; }
add chain inet ikeproxy output { type nat hook output priority dstnat; policy accept; }

# Raw packets crafted by ike_proxy.py are injected into local charon with this mark.
# Keep them out of conntrack; otherwise charon's response can be classified as a
# conntrack reply and bypass the OUTPUT nat redirect that feeds the reverse IKE
# datagram back into the overlay.
add rule inet ikeproxy output_raw meta mark ${MARK_HEX} notrack

# Do not redirect packets generated by the adapter itself.
add rule inet ikeproxy output meta mark ${MARK_HEX} return

# IKE over UDP/500. Destination-specific ports let the adapter route any pair.
add rule inet ikeproxy output ip daddr ${USER1_IP} udp dport 500 redirect to :${USER1_CAP500}
add rule inet ikeproxy output ip daddr ${USER2_IP} udp dport 500 redirect to :${USER2_CAP500}
add rule inet ikeproxy output ip daddr ${USER3_IP} udp dport 500 redirect to :${USER3_CAP500}
add rule inet ikeproxy output ip daddr ${USER4_IP} udp dport 500 redirect to :${USER4_CAP500}
add rule inet ikeproxy output ip daddr ${USER5_IP} udp dport 500 redirect to :${USER5_CAP500}
add rule inet ikeproxy output ip daddr ${USER6_IP} udp dport 500 redirect to :${USER6_CAP500}
add rule inet ikeproxy output ip daddr ${USER7_IP} udp dport 500 redirect to :${USER7_CAP500}
add rule inet ikeproxy output ip daddr ${USER8_IP} udp dport 500 redirect to :${USER8_CAP500}
add rule inet ikeproxy output ip daddr ${USER9_IP} udp dport 500 redirect to :${USER9_CAP500}
add rule inet ikeproxy output ip daddr ${USER10_IP} udp dport 500 redirect to :${USER10_CAP500}
add rule inet ikeproxy output ip daddr ${USER11_IP} udp dport 500 redirect to :${USER11_CAP500}
add rule inet ikeproxy output ip daddr ${USER12_IP} udp dport 500 redirect to :${USER12_CAP500}
add rule inet ikeproxy output ip daddr ${USER13_IP} udp dport 500 redirect to :${USER13_CAP500}

# IKE over UDP/4500 has a 4-byte Non-ESP Marker of 00 00 00 00.
# ESP-in-UDP has a non-zero SPI and bypasses this rule.
add rule inet ikeproxy output ip daddr ${USER1_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER1_CAP4500}
add rule inet ikeproxy output ip daddr ${USER2_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER2_CAP4500}
add rule inet ikeproxy output ip daddr ${USER3_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER3_CAP4500}
add rule inet ikeproxy output ip daddr ${USER4_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER4_CAP4500}
add rule inet ikeproxy output ip daddr ${USER5_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER5_CAP4500}
add rule inet ikeproxy output ip daddr ${USER6_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER6_CAP4500}
add rule inet ikeproxy output ip daddr ${USER7_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER7_CAP4500}
add rule inet ikeproxy output ip daddr ${USER8_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER8_CAP4500}
add rule inet ikeproxy output ip daddr ${USER9_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER9_CAP4500}
add rule inet ikeproxy output ip daddr ${USER10_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER10_CAP4500}
add rule inet ikeproxy output ip daddr ${USER11_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER11_CAP4500}
add rule inet ikeproxy output ip daddr ${USER12_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER12_CAP4500}
add rule inet ikeproxy output ip daddr ${USER13_IP} udp dport 4500 @th,64,32 0x00000000 redirect to :${USER13_CAP4500}
NFT

echo "[OK] nft IKE proxy full-mesh rules installed: UDP/500 -> 15101-15113, IKE UDP/4500 -> 15201-15213, mark ${MARK_HEX} bypass"
